//! Exporters: turn an [`LpcacheConfig`] into the various run forms lpcache
//! accepts — a shell env script, the `lpcache` CLI invocation, a systemd
//! unit, a `docker run` command, the matching `llama-server` command(s), or
//! pretty JSON.
//!
//! The env/CLI exports emit exactly the variables/flags the proxy reads
//! (see `lpcache --help`): a single backend uses `LLAMA_URL` / `N_SLOTS` /
//! `SLOT_SAVE_PATH`, multiple backends use the `BACKENDS` JSON array.

use crate::model::LpcacheConfig;
use std::fmt::Write;

/// The export formats understood by `lpcache-config export` and
/// `POST /api/export`.
pub const FORMATS: &[&str] = &["env", "cli", "systemd", "docker", "llama-server", "json"];

/// Shell-quote a value: unquoted when it only contains safe characters,
/// single-quoted otherwise (`'` escaped as `'\''`).
pub fn shquote(s: &str) -> String {
    if !s.is_empty()
        && s
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '/' | ':' | '@' | '-' | '_' | ',' | '+'))
    {
        s.to_string()
    } else {
        format!("'{}'", s.replace('\'', "'\\''"))
    }
}

/// A shell env script (`export KEY=VALUE` lines, grouped by section).
pub fn to_env_script(cfg: &LpcacheConfig) -> String {
    let mut s = String::new();
    let _ = s.write_str(
        "# lpcache environment configuration — generated by lpcache-config.\n\
         # source this file (or copy the exports) before starting lpcache.\n\n",
    );
    let mut last_section: Option<&str> = None;
    for (section, key, value) in cfg.env_pairs() {
        if last_section != Some(section) {
            let _ = writeln!(s, "# --- {section} ---");
            last_section = Some(section);
        }
        let _ = writeln!(s, "export {key}={}", shquote(&value));
    }
    s
}

/// The single-line `lpcache ...` invocation (values shell-quoted).
pub fn to_cli_command(cfg: &LpcacheConfig) -> String {
    let mut s = "lpcache".to_string();
    for arg in cfg.cli_args() {
        // each arg is "<flag> <value>" — quote the value part
        let (flag, value) = arg.split_once(' ').unwrap_or((arg.as_str(), ""));
        if value.is_empty() {
            s.push_str(&format!(" {flag}"));
        } else {
            s.push_str(&format!(" {flag} {}", shquote(value)));
        }
    }
    s
}

/// Escape a value for a systemd `Environment="..."=` line.
fn systemd_escape(v: &str) -> String {
    v.replace('\\', "\\\\").replace('"', "\\\"")
}

/// A systemd unit file for the proxy (env-style configuration).
pub fn to_systemd(cfg: &LpcacheConfig) -> String {
    let mut s = String::new();
    let _ = s.write_str(
        "# /etc/systemd/system/lpcache.service — generated by lpcache-config.\n\
         # Adjust WorkingDirectory and ExecStart paths to your setup, then:\n\
         #   sudo systemctl daemon-reload && sudo systemctl enable --now lpcache\n\n",
    );
    let _ = s.write_str(
        "[Unit]\n\
         Description=KV-cache aware OpenAI-compatible proxy for llama.cpp (lpcache)\n\
         After=network.target\n\n\
         [Service]\n\
         Type=simple\n\
         WorkingDirectory=/opt/lpcache\n\
         ExecStart=/usr/local/bin/lpcache\n",
    );
    for (_, key, value) in cfg.env_pairs() {
        let _ = writeln!(s, "Environment=\"{key}={}\"", systemd_escape(&value));
    }
    let _ = s.write_str(
        "\nRestart=on-failure\n\
         RestartSec=2\n\n\
         [Install]\n\
         WantedBy=multi-user.target\n",
    );
    s
}

/// Reduce a path to a safe volume name (slashes → `_`, leading dot/dash
/// dropped, empty → `data`).
fn volume_name(p: &str) -> String {
    let flat: String = p.trim().chars().map(|c| (c == '/' || c == '.').then(|| '_').unwrap_or(c))
        .collect();
    let flat = flat.trim_matches('_').to_string();
    if flat.is_empty() {
        "data".to_string()
    } else {
        flat
    }
}

/// A `docker run` command (env-style configuration; image name and volume
/// mounts are placeholders to adjust).
pub fn to_docker(cfg: &LpcacheConfig) -> String {
    let mut s = String::new();
    let _ = s.write_str(
        "# docker run for lpcache — generated by lpcache-config.\n\
         # Adjust the image name and the volume mounts to your setup.\n",
    );
    let mut lines: Vec<String> = vec![
        "docker run -d \\".into(),
        "  --name lpcache \\".into(),
        format!("  -p {}:{} \\", cfg.proxy.port, cfg.proxy.port),
    ];
    // mount the meta dir and any slot-save / result-cache dirs so the
    // KV/meta state persists
    let mut volumes: Vec<String> = Vec::new();
    let mut seen = std::collections::HashSet::new();
    let add_vol = |volumes: &mut Vec<String>, seen: &mut std::collections::HashSet<String>, p: &str| {
        let name = volume_name(p);
        if seen.insert(name.clone()) {
            volumes.push(format!("-v \"$PWD/{name}:/data/{name}\""));
        }
    };
    add_vol(&mut volumes, &mut seen, &cfg.kv_cache.meta_dir);
    for be in &cfg.backends {
        if !be.slot_save_path.trim().is_empty() {
            add_vol(&mut volumes, &mut seen, be.slot_save_path.trim());
        }
    }
    if !cfg.prefilter.result_cache_dir.trim().is_empty() {
        add_vol(&mut volumes, &mut seen, cfg.prefilter.result_cache_dir.trim());
    }
    for v in &volumes {
        lines.push(format!("  {v} \\"));
    }
    for (_, key, value) in cfg.env_pairs() {
        lines.push(format!("  -e {}={} \\", key, shquote(&value)));
    }
    // the last -e line must not end with a continuation backslash
    let last = lines.last_mut().expect("at least one -e line");
    *last = last.trim_end_matches(' ').trim_end_matches('\\').to_string();
    lines.push("  lpcache:latest".into());
    let _ = writeln!(s, "{}", lines.join("\n"));
    s
}


/// The matching `llama-server` command(s) — one per configured backend,
/// with the flags the proxy depends on (`-np`, `--api-key`,
/// `--slot-save-path`). The model path is a placeholder.
pub fn to_llama_server(cfg: &LpcacheConfig) -> String {
    let mut s = String::new();
    let _ = s.write_str(
        "# Matching llama-server commands — generated by lpcache-config.\n\
         # Replace ./model.gguf with your model path; the proxy only works\n\
         # correctly when the backend flags match the proxy settings.\n",
    );
    if cfg.backends.is_empty() {
        let _ = writeln!(s, "# (no backends configured)");
        return s;
    }
    for (i, be) in cfg.backends.iter().enumerate() {
        let (host, port) = host_port_from_url(&be.url);
        let _ = writeln!(
            s,
            "\n# backend {} ({} slot(s)): {}",
            i + 1,
            be.n_slots,
            be.url
        );
        let mut cmd = format!("llama-server -m ./model.gguf -np {}", be.n_slots);
        if !cfg.proxy.api_key.trim().is_empty() {
            cmd.push_str(&format!(" --api-key {}", cfg.proxy.api_key));
        }
        let save = if be.slot_save_path.trim().is_empty() {
            cfg.kv_cache.slot_save_path.trim().to_string()
        } else {
            be.slot_save_path.trim().to_string()
        };
        if !be.kv_cache {
            let _ = writeln!(
                s,
                "# note: kv_cache is disabled for this backend (llama-server < 1.05.40)"
            );
        } else if !save.is_empty() {
            cmd.push_str(&format!(" --slot-save-path {}", save));
        }
        cmd.push_str(&format!(" --host {host} --port {port}"));
        let _ = writeln!(s, "{cmd}");
    }
    s
}

/// The configuration as pretty JSON (the configurator's own file model).
pub fn to_json(cfg: &LpcacheConfig) -> String {
    serde_json::to_string_pretty(cfg).unwrap_or_default()
}

/// Dispatch an export by format name; `Err` for an unknown format.
pub fn export(cfg: &LpcacheConfig, format: &str) -> Result<String, String> {
    match format {
        "env" => Ok(to_env_script(cfg)),
        "cli" => Ok(to_cli_command(cfg)),
        "systemd" => Ok(to_systemd(cfg)),
        "docker" => Ok(to_docker(cfg)),
        "llama-server" => Ok(to_llama_server(cfg)),
        "json" => Ok(to_json(cfg)),
        other => Err(format!(
            "unknown format {other:?} (one of: {})",
            FORMATS.join(", ")
        )),
    }
}

/// Split `scheme://host:port/...` into `(host, port)`; defaults
/// `http`→80, `https`→443 when no port is given.
fn host_port_from_url(url: &str) -> (String, u16) {
    let url = url.trim();
    let (rest, default_port) = if let Some(r) = url.strip_prefix("https://") {
        (r, 443u16)
    } else if let Some(r) = url.strip_prefix("http://") {
        (r, 80u16)
    } else {
        (url, 80u16)
    };
    let hostpart = rest.split('/').next().unwrap_or(rest);
    match hostpart.rsplit_once(':') {
        Some((host, port)) => (host.to_string(), port.parse::<u16>().unwrap_or(default_port)),
        None => (hostpart.to_string(), default_port),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shquote_behaviour() {
        assert_eq!(shquote("8081"), "8081");
        assert_eq!(shquote("a/b:c"), "a/b:c");
        assert_eq!(shquote("a b"), "'a b'");
        assert_eq!(shquote("a'b"), "'a'\\''b'");
    }

    #[test]
    fn env_script_groups_and_quotes() {
        let mut cfg = LpcacheConfig::default();
        cfg.proxy.api_key = "p a55".into();
        let s = to_env_script(&cfg);
        assert!(s.starts_with("# lpcache environment configuration"));
        assert!(s.contains("# --- proxy ---"));
        assert!(s.contains("export PORT=8081"));
        assert!(s.contains("export LLAMA_API_KEY='p a55'"));
        assert!(s.contains("export LLAMA_URL=http://127.0.0.1:8000"));
        assert!(s.contains("export META_DIR=kv_meta"));
    }

    #[test]
    fn cli_command_is_single_line() {
        let cfg = LpcacheConfig::default();
        let s = to_cli_command(&cfg);
        assert!(!s.contains('\n'));
        assert!(s.starts_with("lpcache --port 8081 "));
        assert!(s.contains("--lcp-th 0.1"));
    }

    #[test]
    fn systemd_unit_shape() {
        let cfg = LpcacheConfig::default();
        let s = to_systemd(&cfg);
        assert!(s.contains("[Unit]"));
        assert!(s.contains("[Service]"));
        assert!(s.contains("[Install]"));
        assert!(s.contains("Environment=\"PORT=8081\""));
    }

    #[test]
    fn docker_run_shape() {
        let mut cfg = LpcacheConfig::default();
        cfg.backends[0].slot_save_path = "kvcache".into();
        let s = to_docker(&cfg);
        assert!(s.starts_with("# docker run"));
        assert!(s.contains("-p 8081:8081 \\"));
        assert!(s.contains("-e PORT=8081 \\"));
        assert!(s.ends_with("  lpcache:latest\n"));
        assert!(!s.lines().last().unwrap().ends_with('\\'));
    }

    #[test]
    fn llama_server_flags() {
        let mut cfg = LpcacheConfig::default();
        cfg.proxy.api_key = "777".into();
        cfg.kv_cache.slot_save_path = "kvcache".into();
        let s = to_llama_server(&cfg);
        assert!(s.contains(
            "llama-server -m ./model.gguf -np 1 --api-key 777 --slot-save-path kvcache --host 127.0.0.1 --port 8000"
        ));
    }

    #[test]
    fn host_port_parsing() {
        assert_eq!(host_port_from_url("http://127.0.0.1:8000"), ("127.0.0.1".into(), 8000));
        assert_eq!(host_port_from_url("https://example.com/x"), ("example.com".into(), 443));
        assert_eq!(host_port_from_url("http://h"), ("h".into(), 80));
    }

    #[test]
    fn unknown_format_errors() {
        let cfg = LpcacheConfig::default();
        assert!(export(&cfg, "nope").is_err());
        assert!(export(&cfg, "json").unwrap().contains("\"proxy\""));
    }
}

